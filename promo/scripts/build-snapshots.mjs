// Turns the captured DOM (assets/captures/dom/*.html) into a TS module the
// film imports: scripts and inline handlers stripped, nothing else changed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PROMO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(PROMO, 'assets', 'captures', 'dom');
const out = path.join(PROMO, 'src', 'ui', 'snapshots.generated.ts');
const snaps = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.html')).sort()) {
  let html = fs.readFileSync(path.join(dir, f), 'utf8')
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/\son[a-z]+="[^"]*"/gi, '')
    .replace(/<!--[\s\S]*?-->/g, '');
  snaps[f.replace(/\.html$/, '')] = html;
}
const imgs = [...new Set(Object.values(snaps).flatMap((h) => [...h.matchAll(/<img[^>]*src="([^"]{0,40})/g)].map((m) => m[1])))];
fs.writeFileSync(out, `/* Generated by scripts/build-snapshots.mjs from assets/captures/dom. Do not edit. */\n/* eslint-disable */\nexport const SNAP: Record<string, string> = ${JSON.stringify(snaps)};\n`);
console.log(`wrote ${path.relative(PROMO, out)}: ${Object.keys(snaps).length} snapshots, ${(fs.statSync(out).size / 1024).toFixed(0)} KB; img srcs: ${imgs.join(' | ') || 'none'}`);
